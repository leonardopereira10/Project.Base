namespace Project.Base.Enumerators;

/// <summary>
/// Specifies the sort order direction used in queries and result sets.
/// </summary>
public enum EnumOrder
{
    /// <summary>
    /// Descending order (from highest to lowest value).
    /// </summary>
    DESCENDING,

    /// <summary>
    /// Ascending order (from lowest to highest value).
    /// </summary>
    ASCENDING
}
